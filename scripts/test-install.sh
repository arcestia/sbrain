#!/usr/bin/env bash
# Test the installer, the bootstrap, and the format hook end to end, in a throwaway home folder
# with stub agent CLIs. Nothing outside a temporary folder changes.
#
# Usage: scripts/test-install.sh
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
FH="$WORK/home" STUB="$WORK/bin" LOG="$WORK/calls.log"
mkdir -p "$FH" "$STUB"
: > "$LOG"

for c in codex copilot opencode gemini agy pi; do
  printf '#!/bin/sh\necho "%s $*" >> "%s"\n' "$c" "$LOG" > "$STUB/$c"
  chmod +x "$STUB/$c"
done
# The claude stub remembers what it installed, so a second run exercises the update path.
cat > "$STUB/claude" <<EOF
#!/bin/sh
echo "claude \$*" >> "$LOG"
case "\$*" in
  "plugin marketplace list") grep -q "marketplace add" "$LOG" && ! grep -q "marketplace remove" "$LOG" && echo "  sbrain" ;;
  "plugin list") grep -q "plugin install sbrain@sbrain" "$LOG" && ! grep -q "plugin uninstall" "$LOG" && echo "  sbrain@sbrain" ;;
esac
exit 0
EOF
chmod +x "$STUB/claude"
# Stubs shadow any real agent CLI, then python3 and the base system tools.
SAFE_PATH="$STUB:$(dirname "$(command -v python3)"):/usr/bin:/bin:/usr/sbin:/sbin"
installer() { HOME="$FH" PATH="$SAFE_PATH" "$ROOT/scripts/install.sh" "$@"; }

fails=0
check() {
  local desc="$1"; shift
  if "$@" >/dev/null 2>&1; then printf 'ok    %s\n' "$desc"; else printf 'FAIL  %s\n' "$desc"; fails=$((fails + 1)); fi
}
same_json() { python3 -I -c 'import json, sys; sys.exit(json.load(open(sys.argv[1])) != json.load(open(sys.argv[2])))' "$1" "$2"; }
count_ours() { python3 -I -c 'import sys; print(open(sys.argv[1]).read().count(sys.argv[2]))' "$1" "$ROOT/hooks/format-on-edit.sh"; }
links_into_skills() { local n=0 l; for l in "$1"/*; do [ -L "$l" ] && case "$(readlink "$l")" in "$ROOT/skills"/*) n=$((n + 1)) ;; esac || true; done; echo "$n"; }

total=0
for d in "$ROOT"/skills/*/; do total=$((total + 1)); done

# User state that must survive an install and an uninstall.
mkdir -p "$FH/.cursor/agents" "$FH/.gemini" "$FH/.agents/skills/how"
echo '{"version":1,"hooks":{"afterFileEdit":[{"command":"echo user-hook"}]}}' > "$FH/.cursor/hooks.json"
echo '{"theme":"dark"}' > "$FH/.gemini/settings.json"
printf -- '---\nname: comment-sicko\ndescription: mine\n---\nmine\n' > "$FH/.cursor/agents/comment-sicko.md"
cp "$FH/.cursor/hooks.json" "$WORK/cursor.json"
cp "$FH/.gemini/settings.json" "$WORK/gemini.json"
cp "$FH/.cursor/agents/comment-sicko.md" "$WORK/sicko.md"
before=$(cd "$FH" && find . | sort)

echo "== install"
installer >/dev/null
check "Claude Code plugin installed through its CLI" grep -q "claude plugin install sbrain@sbrain" "$LOG"
check "shared skill links: all but the user's own 'how'" test "$(links_into_skills "$FH/.agents/skills")" -eq $((total - 1))
check "the user's own 'how' skill is untouched" test -d "$FH/.agents/skills/how" -a ! -L "$FH/.agents/skills/how"
check "Antigravity skill links" test "$(links_into_skills "$FH/.gemini/config/skills")" -eq "$total"
check "Cursor delegate agent written" grep -q "generated by SBrain" "$FH/.cursor/agents/skiddle-agent.md"
check "the user's own Cursor comment-sicko is untouched" cmp -s "$WORK/sicko.md" "$FH/.cursor/agents/comment-sicko.md"
check "Codex agents written as TOML" test -f "$FH/.codex/agents/skiddle-agent.toml" -a -f "$FH/.codex/agents/comment-sicko.toml"
check "Copilot agents written" test -f "$FH/.copilot/agents/skiddle-agent.agent.md" -a -f "$FH/.copilot/agents/comment-sicko.agent.md"
check "OpenCode agents are subagents" grep -q "^mode: subagent" "$FH/.config/opencode/agents/skiddle-agent.md"
check "Gemini CLI agents written" test -f "$FH/.gemini/agents/comment-sicko.md"
check "portable agents for Goose" test -f "$FH/.agents/agents/skiddle-agent.md"
check "Cursor hook added, user hook kept" grep -q "user-hook" "$FH/.cursor/hooks.json"
check "Cursor hook present once" test "$(count_ours "$FH/.cursor/hooks.json")" -eq 1
check "Codex hook present" test "$(count_ours "$FH/.codex/hooks.json")" -eq 1
check "Copilot hook file present" test "$(count_ours "$FH/.copilot/hooks/sbrain-format.json")" -eq 1
check "Gemini hook added, theme kept" python3 -I -c 'import json, sys; d = json.load(open(sys.argv[1])); sys.exit(not (d["theme"] == "dark" and "AfterTool" in d["hooks"]))' "$FH/.gemini/settings.json"
if python3 -c 'import tomllib' 2>/dev/null; then
  check "Codex TOML parses" python3 -I -c 'import glob, sys, tomllib; [tomllib.load(open(f, "rb")) for f in glob.glob(sys.argv[1] + "/*.toml")]' "$FH/.codex/agents"
fi

echo "== reinstall"
ln -s "$ROOT/skills/retired-skill" "$FH/.agents/skills/retired-skill"
installer >/dev/null
check "hooks are not duplicated" test "$(count_ours "$FH/.cursor/hooks.json")" -eq 1 -a "$(count_ours "$FH/.codex/hooks.json")" -eq 1
check "a link to a removed skill is cleaned up" test ! -L "$FH/.agents/skills/retired-skill"
check "only the user's original configs are backed up" test "$(cd "$FH" && find . -name '*.sbrain-backup' | wc -l | tr -d ' ')" -eq 2
check "Claude Code plugin updated, not reinstalled, when present" grep -q "claude plugin update sbrain@sbrain" "$LOG"
check "Claude Code marketplace refreshed, not added twice" test "$(grep -c "claude plugin marketplace add" "$LOG")" -eq 1

echo "== doctor"
doctor=$(installer --doctor)
check "doctor reports Cursor fully installed" grep -q "cursor .* agents yes, hook yes" <<<"$doctor"
check "doctor reports the Claude Code plugin" grep -q "claude .* plugin yes" <<<"$doctor"
check "doctor reports missing model files" grep -q "missing  $FH/.agents/sbrain-models.md" <<<"$doctor"

echo "== uninstall"
installer --uninstall >/dev/null
check "Claude Code plugin removed through its CLI" grep -q "claude plugin uninstall sbrain@sbrain" "$LOG"
check "Cursor hooks restored exactly" same_json "$WORK/cursor.json" "$FH/.cursor/hooks.json"
check "Gemini settings restored exactly" same_json "$WORK/gemini.json" "$FH/.gemini/settings.json"
check "only the original files remain" test "$(cd "$FH" && find . | sort)" = "$before"

echo "== bootstrap"
if git -C "$ROOT" rev-parse HEAD >/dev/null 2>&1; then
  boot() { HOME="$FH" PATH="$SAFE_PATH" SBRAIN_REPO="file://$ROOT" SBRAIN_HOME="$WORK/clone" bash "$ROOT/scripts/bootstrap.sh" "$@"; }
  check "bootstrap clones and runs the installer" boot --list
  check "the clone is a git repository" test -d "$WORK/clone/.git"
  check "a second bootstrap updates the clone" boot --list
fi

echo "== format hook"
if command -v gofmt >/dev/null 2>&1; then
  mkdir -p "$WORK/hook"
  for shape in claude cursor copilot codex; do
    f="$WORK/hook/$shape.go"
    printf 'package main\nfunc  f(){}\n' > "$f"
    case "$shape" in
      claude) printf '{"tool_input":{"file_path":"%s"}}' "$f" ;;
      cursor) printf '{"file_path":"%s"}' "$f" ;;
      copilot) python3 -I -c 'import json, sys; print(json.dumps({"toolArgs": json.dumps({"path": sys.argv[1]})}))' "$f" ;;
      codex) python3 -I -c 'import json, sys; print(json.dumps({"cwd": sys.argv[1], "tool_input": {"command": "*** Begin Patch\n*** Update File: codex.go\n*** End Patch"}}))' "$WORK/hook" ;;
    esac | "$ROOT/hooks/format-on-edit.sh"
    check "hook formats a $shape edit" grep -q "^func f() {}" "$f"
  done
else
  echo "skip  gofmt is not installed"
fi

echo
if [ "$fails" -eq 0 ]; then echo "All installer tests passed."; else echo "$fails installer test(s) failed."; exit 1; fi
