#!/usr/bin/env bash
# Install SBrain into the coding agents on this machine, or remove it.
#
# Usage: scripts/install.sh [--only <t1,t2>] [--update] [--doctor] [--uninstall] [--dry-run] [--list]
#
#   --update     pull the latest SBrain into this clone, then install again (safe to repeat)
#   --doctor     report what is installed where, which toolchains exist, and what to do next
#   --uninstall  remove only what SBrain added (every target, or those named with --only)
#   --dry-run    print what would change and change nothing
#   --list       show which agents were detected
#
# Targets:
#   claude       Claude Code plugin from this folder's marketplace (skills, agents, format hook)
#   cursor       skills link, ~/.cursor/agents/, afterFileEdit hook in ~/.cursor/hooks.json
#   codex        skills link, ~/.codex/agents/*.toml, PostToolUse hook in ~/.codex/hooks.json
#   copilot      skills link, ~/.copilot/agents/*.agent.md, ~/.copilot/hooks/sbrain-format.json
#   opencode     skills link, ~/.config/opencode/agents/ (mode: subagent)
#   gemini       skills link, ~/.gemini/agents/, AfterTool hook in ~/.gemini/settings.json
#   antigravity  skills linked into ~/.gemini/config/skills/
#   pi           skills link
#   skills       the shared links in ~/.agents/skills/ (read by Cursor, Codex, Copilot, OpenCode,
#                Gemini CLI, Pi, Amp, Goose, Devin, and other Agent Skills clients) and the
#                portable agents in ~/.agents/agents/ (Goose)
#
# With no --only, it installs for every agent it detects (a CLI on PATH or a config folder).
# Skills are symlinks into this folder, so edits here apply at once. Generated agent files carry a
# "generated by SBrain" marker, and the installer never overwrites a file without it. Before it
# changes a JSON config that already exists, it saves a .sbrain-backup copy once. --uninstall
# removes only what SBrain added.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SKILLS="$ROOT/skills"
HOOK="$ROOT/hooks/format-on-edit.sh"
MARK="generated by SBrain install.sh"
ALL="claude cursor codex copilot opencode gemini antigravity pi skills"

only="" uninstall=0 dry=0 list=0 update=0 doctor=0 rest=""
while [ $# -gt 0 ]; do
  case "$1" in
    --only) only=$(printf '%s' "${2:?--only needs a list}" | tr ',' ' '); rest="$rest --only $2"; shift 2 ;;
    --update) update=1; shift ;;
    --doctor) doctor=1; shift ;;
    --uninstall) uninstall=1; rest="$rest --uninstall"; shift ;;
    --dry-run) dry=1; rest="$rest --dry-run"; shift ;;
    --list) list=1; shift ;;
    -h|--help) awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"; exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
done

has() { command -v "$1" >/dev/null 2>&1; }
say() { printf '%s\n' "$*"; }

if [ "$update" = 1 ]; then
  if ! git -C "$ROOT" rev-parse --abbrev-ref '@{upstream}' >/dev/null 2>&1; then
    say "This SBrain folder has no upstream branch to pull from. Reinstalling from it as it is."
  elif [ "$dry" = 1 ]; then
    say "Dry run: would pull the latest SBrain into $ROOT."
  else
    say "Pulling the latest SBrain into $ROOT"
    git -C "$ROOT" pull --ff-only --quiet || { say "Pull failed (local changes, or the branch has diverged). Fix it in $ROOT, then rerun."; exit 1; }
  fi
  # Run the freshly pulled installer, so an update can also change how SBrain installs.
  # shellcheck disable=SC2086
  exec "$ROOT/scripts/install.sh" $rest
fi
run() { if [ "$dry" = 1 ]; then say "  would run: $*"; else "$@"; fi; }

detected() {
  case "$1" in
    claude) has claude ;;
    cursor) has cursor || has cursor-agent || [ -d "$HOME/.cursor" ] || [ -d /Applications/Cursor.app ] ;;
    codex) has codex || [ -d "${CODEX_HOME:-$HOME/.codex}" ] ;;
    copilot) has copilot || [ -d "$HOME/.copilot" ] ;;
    opencode) has opencode || [ -d "$HOME/.config/opencode" ] ;;
    gemini) has gemini || [ -f "$HOME/.gemini/settings.json" ] ;;
    antigravity) has agy || [ -d "$HOME/.gemini/config" ] || [ -d "$HOME/.gemini/antigravity-cli" ] ;;
    pi) has pi || [ -d "$HOME/.pi" ] ;;
    skills) return 1 ;;
  esac
}

if [ "$list" = 1 ]; then
  for t in $ALL; do
    if [ "$t" = skills ]; then say "skills       (shared; added with any target that reads ~/.agents/skills)"
    elif detected "$t"; then say "$(printf '%-12s' "$t") detected"
    else say "$(printf '%-12s' "$t") not found"; fi
  done
  exit 0
fi

# ---- doctor -----------------------------------------------------------------------------------

count_links() {
  local n=0 l
  [ -d "$1" ] || { echo 0; return; }
  for l in "$1"/*; do
    [ -L "$l" ] && [ -e "$l" ] && case "$(readlink "$l")" in "$SKILLS"/*) n=$((n + 1)) ;; esac || true
  done
  echo "$n"
}
yes_no() { if "$@"; then printf 'yes'; else printf 'no'; fi; }
agents_in() { [ -f "$1/skiddle-agent$2" ] && grep -q "$MARK" "$1/skiddle-agent$2"; }
hook_in() { [ -f "$1" ] && grep -qF "$HOOK" "$1"; }

if [ "$doctor" = 1 ]; then
  total=0; for d in "$SKILLS"/*/; do total=$((total + 1)); done
  version=$(sed -nE 's/.*"version":[[:space:]]*"([^"]+)".*/\1/p' "$ROOT/.claude-plugin/plugin.json" | head -n1)
  say "SBrain $version at $ROOT ($(git -C "$ROOT" log -1 --format='%h, %cs' 2>/dev/null || echo 'not a git clone'))"
  shared="skills $(count_links "$HOME/.agents/skills")/$total"
  codex_home=${CODEX_HOME:-$HOME/.codex}
  say ""
  say "Agents"
  for t in claude cursor codex copilot opencode gemini antigravity pi; do
    if detected "$t"; then found="found"; else found="-"; fi
    case "$t" in
      claude) state="plugin $(yes_no eval 'has claude && claude plugin list 2>/dev/null | grep -q "sbrain@sbrain"')" ;;
      cursor) state="$shared, agents $(yes_no agents_in "$HOME/.cursor/agents" .md), hook $(yes_no hook_in "$HOME/.cursor/hooks.json")" ;;
      codex) state="$shared, agents $(yes_no agents_in "$codex_home/agents" .toml), hook $(yes_no hook_in "$codex_home/hooks.json") (trust it once with /hooks)" ;;
      copilot) state="$shared, agents $(yes_no agents_in "$HOME/.copilot/agents" .agent.md), hook $(yes_no hook_in "$HOME/.copilot/hooks/sbrain-format.json")" ;;
      opencode) state="$shared, agents $(yes_no agents_in "$HOME/.config/opencode/agents" .md), no hook support" ;;
      gemini) state="$shared, agents $(yes_no agents_in "$HOME/.gemini/agents" .md), hook $(yes_no hook_in "$HOME/.gemini/settings.json")" ;;
      antigravity) state="skills $(count_links "$HOME/.gemini/config/skills")/$total, no agents or hook" ;;
      pi) state="$shared, no subagents or hook" ;;
    esac
    printf '  %-12s %-6s %s\n' "$t" "$found" "$state"
  done
  say ""
  say "Toolchains (a missing one runs in the repository's container instead)"
  line=""
  for c in git python3 go gofmt cargo rustfmt ruby bundle php composer node bun; do
    if has "$c"; then line="$line  $c ok"; else line="$line  $c missing"; fi
  done
  say " $line"
  say ""
  say "Model files (run setup-sbrain once in each agent to write one)"
  for f in "$HOME/.claude/rules/sbrain-models.md" "$HOME/.cursor/rules/sbrain-models.mdc" "$HOME/.agents/sbrain-models.md"; do
    if [ -f "$f" ]; then say "  ok       $f"; else say "  missing  $f"; fi
  done
  has python3 || say "python3 is missing: the format hook and the installer's JSON edits need it."
  exit 0
fi

targets=""
if [ -n "$only" ]; then
  for t in $only; do
    case " $ALL " in *" $t "*) targets="$targets $t" ;; *) echo "Unknown target: $t (one of: $ALL)" >&2; exit 2 ;; esac
  done
elif [ "$uninstall" = 1 ]; then
  targets=" $ALL"
else
  for t in $ALL; do detected "$t" && targets="$targets $t"; done
fi
[ -n "$targets" ] || { say "No agents detected. Use --only <target>, or --list."; exit 0; }

# Every target except claude and antigravity reads the shared ~/.agents/skills links.
if [ "$uninstall" = 0 ]; then
  for t in $targets; do
    case "$t" in cursor|codex|copilot|opencode|gemini|pi) case " $targets " in *" skills "*) ;; *) targets="$targets skills" ;; esac ;; esac
  done
fi

# ---- skills links -----------------------------------------------------------------------------

link_skills() {
  local dest="$1" name src link
  run mkdir -p "$dest"
  # Drop links to skills that no longer exist, such as one renamed or removed by an update.
  for link in "$dest"/*; do
    [ -L "$link" ] && [ ! -e "$link" ] && case "$(readlink "$link")" in "$SKILLS"/*) run rm "$link" ;; esac || true
  done
  for src in "$SKILLS"/*/; do
    src=${src%/}; name=$(basename "$src"); link="$dest/$name"
    if [ -L "$link" ]; then
      case "$(readlink "$link")" in "$SKILLS"/*) [ "$(readlink "$link")" = "$src" ] && continue; run rm "$link" ;; *) say "  skip $link (a link SBrain did not make)"; continue ;; esac
    elif [ -e "$link" ]; then
      say "  skip $link (already exists)"; continue
    fi
    run ln -s "$src" "$link"
  done
  [ "$dry" = 1 ] || say "  skills linked in $dest"
}

unlink_skills() {
  local dest="$1" link
  [ -d "$dest" ] || return 0
  for link in "$dest"/*; do
    [ -L "$link" ] || continue
    case "$(readlink "$link")" in "$SKILLS"/*) run rm "$link" ;; esac
  done
  say "  SBrain skill links removed from $dest"
}

# ---- agent files ------------------------------------------------------------------------------

body_of() { awk 'NR==1 && /^---$/ {f=1; next} f && /^---$/ {f=0; next} !f' "$1"; }

DELEGATE_DESC="SBrain delegate for code-writing and helper tasks in a skiddle-mode run. It reads the skiddle-mode skill in full before any work."
SICKO_DESC=$(sed -n 's/^description: //p' "$ROOT/agents/comment-sicko.md" | head -n1)

delegate_body() {
  cat <<EOF
# Skiddle subagent

You are a delegate in an SBrain \`skiddle-mode\` run. The agent that started you owns the playbook and the todo list. Before any work, read \`$SKILLS/skiddle-mode/worker.md\`, then \`$SKILLS/skiddle-mode/SKILL.md\` in full, including its Principles index, then your agent's adapter in \`$SKILLS/skiddle-mode/references/harness/\`. Read a leaf \`principle-*\` skill whenever you apply that principle. Before you edit a file, read the language skill that skiddle-mode's Non-negotiables map its extension to.
EOF
}

sicko_body() { body_of "$ROOT/agents/comment-sicko.md"; }

# write_agent <path> <format> <name> <description> <body-function>
write_agent() {
  local path="$1" fmt="$2" name="$3" desc="$4" body tmp
  if [ -e "$path" ] && ! grep -q "$MARK" "$path"; then say "  skip $path (not made by SBrain)"; return 0; fi
  body=$("$5")
  if [ "$dry" = 1 ]; then say "  would write $path"; return 0; fi
  mkdir -p "$(dirname "$path")"; tmp="$path.tmp.$$"
  case "$fmt" in
    toml)
      case "$body" in *"'''"*) echo "Agent body for $name contains ''' and cannot be a TOML literal" >&2; return 1 ;; esac
      { printf '# %s. Edits here are overwritten on the next install.\n' "$MARK"
        printf 'name = "%s"\ndescription = "%s"\n' "$name" "$desc"
        printf "developer_instructions = '''\n%s\n'''\n" "$body"; } > "$tmp" ;;
    *)
      { printf -- '---\nname: %s\ndescription: "%s"\n' "$name" "$desc"
        case "$fmt" in
          cursor) printf 'model: inherit\n' ;;
          opencode) printf 'mode: subagent\n' ;;
        esac
        printf -- '---\n\n<!-- %s. Edits here are overwritten on the next install. -->\n\n%s\n' "$MARK" "$body"; } > "$tmp" ;;
  esac
  mv "$tmp" "$path"
  say "  wrote $path"
}

remove_agent() {
  local path="$1"
  [ -e "$path" ] || return 0
  if grep -q "$MARK" "$path"; then run rm "$path"; say "  removed $path"; else say "  kept $path (not made by SBrain)"; fi
}

# agents <dir> <format> <extension>
agents() {
  write_agent "$1/skiddle-agent$3" "$2" skiddle-agent "$DELEGATE_DESC" delegate_body
  write_agent "$1/comment-sicko$3" "$2" comment-sicko "$SICKO_DESC" sicko_body
}
unagents() { remove_agent "$1/skiddle-agent$2"; remove_agent "$1/comment-sicko$2"; }

# ---- JSON hook configs (merged with python3, keeping everything else) --------------------------

# json_hook <add|remove> <file> <style> ; style: cursor | nested:<Event>:<matcher> | own:<Event>:<matcher>
json_hook() {
  local action="$1" file="$2" style="$3"
  if [ "$dry" = 1 ]; then say "  would $action the format hook in $file"; return 0; fi
  if [ "$action" = remove ] && [ ! -f "$file" ]; then return 0; fi
  has python3 || { say "  skip $file (python3 is needed to edit JSON)"; return 0; }
  mkdir -p "$(dirname "$file")"
  python3 -I - "$action" "$file" "$style" "$HOOK" <<'PY'
import json, os, sys

action, path, style, hook = sys.argv[1:5]
quoted = '"%s"' % hook if " " in hook else hook

try:
    with open(path) as fh:
        text = fh.read()
    data = json.loads(text) if text.strip() else {}
except FileNotFoundError:
    data = {}
except ValueError:
    print("  skip %s (not plain JSON; add the hook by hand: %s)" % (path, quoted))
    sys.exit(0)

def ours(entry):
    return isinstance(entry, dict) and hook in json.dumps(entry)

backup = path + ".sbrain-backup"
own = style.startswith("own:")
# Back up the user's original file once, before SBrain first touches it.
if action == "add" and not own and os.path.exists(path) and not os.path.exists(backup) and hook not in text:
    with open(backup, "w") as fh:
        fh.write(text)

hooks = data.setdefault("hooks", {})
if style == "cursor":
    data.setdefault("version", 1)
    entries = hooks.setdefault("afterFileEdit", [])
    entries[:] = [e for e in entries if not ours(e)]
    if action == "add":
        entries.append({"command": quoted})
    if not entries:
        del hooks["afterFileEdit"]
else:
    _, event, matcher = style.split(":", 2)
    entries = hooks.setdefault(event, [])
    entries[:] = [e for e in entries if not ours(e)]
    if action == "add":
        entries.append({"matcher": matcher, "hooks": [{"type": "command", "command": quoted, "timeout": 30}]})
    if not entries:
        del hooks[event]
if not hooks:
    del data["hooks"]

if action == "remove":
    original = None
    if os.path.exists(backup):
        try:
            original = json.load(open(backup))
        except ValueError:
            original = None
    if not data and (own or original in (None, {})):
        os.remove(path)
        if original is not None:
            os.remove(backup)
        print("  removed %s" % path)
        sys.exit(0)
    if original is not None and original == data:
        os.remove(backup)

tmp = path + ".tmp"
with open(tmp, "w") as fh:
    json.dump(data, fh, indent=2)
    fh.write("\n")
os.replace(tmp, path)
print("  %s the format hook in %s" % ("added" if action == "add" else "removed", path))
PY
}

# ---- targets ----------------------------------------------------------------------------------

install_target() {
  case "$1" in
    claude)
      has claude || { say "  skip: the claude CLI is not on PATH"; return 0; }
      if claude plugin marketplace list 2>/dev/null | grep -q "sbrain"; then run claude plugin marketplace update sbrain
      else run claude plugin marketplace add "$ROOT"; fi
      if claude plugin list 2>/dev/null | grep -q "sbrain@sbrain"; then run claude plugin update sbrain@sbrain
      else run claude plugin install sbrain@sbrain; fi
      say "  start a new Claude Code session, then run /sbrain:setup-sbrain" ;;
    cursor)
      agents "$HOME/.cursor/agents" cursor .md
      json_hook add "$HOME/.cursor/hooks.json" cursor ;;
    codex)
      agents "${CODEX_HOME:-$HOME/.codex}/agents" toml .toml
      json_hook add "${CODEX_HOME:-$HOME/.codex}/hooks.json" "nested:PostToolUse:apply_patch|Edit|Write"
      say "  in Codex, trust the new hook once with /hooks" ;;
    copilot)
      agents "$HOME/.copilot/agents" copilot .agent.md
      json_hook add "$HOME/.copilot/hooks/sbrain-format.json" "own:PostToolUse:edit|create" ;;
    opencode)
      agents "$HOME/.config/opencode/agents" opencode .md ;;
    gemini)
      agents "$HOME/.gemini/agents" gemini .md
      json_hook add "$HOME/.gemini/settings.json" "nested:AfterTool:write_file|replace" ;;
    antigravity)
      link_skills "$HOME/.gemini/config/skills" ;;
    pi) : ;;
    skills)
      link_skills "$HOME/.agents/skills"
      agents "$HOME/.agents/agents" generic .md ;;
  esac
}

uninstall_target() {
  case "$1" in
    claude)
      has claude || return 0
      run claude plugin uninstall sbrain@sbrain || true
      run claude plugin marketplace remove sbrain || true ;;
    cursor) unagents "$HOME/.cursor/agents" .md; json_hook remove "$HOME/.cursor/hooks.json" cursor ;;
    codex) unagents "${CODEX_HOME:-$HOME/.codex}/agents" .toml; json_hook remove "${CODEX_HOME:-$HOME/.codex}/hooks.json" "nested:PostToolUse:apply_patch|Edit|Write" ;;
    copilot) unagents "$HOME/.copilot/agents" .agent.md; json_hook remove "$HOME/.copilot/hooks/sbrain-format.json" "own:PostToolUse:edit|create" ;;
    opencode) unagents "$HOME/.config/opencode/agents" .md ;;
    gemini) unagents "$HOME/.gemini/agents" .md; json_hook remove "$HOME/.gemini/settings.json" "nested:AfterTool:write_file|replace" ;;
    antigravity) unlink_skills "$HOME/.gemini/config/skills" ;;
    pi) : ;;
    skills) unlink_skills "$HOME/.agents/skills"; unagents "$HOME/.agents/agents" .md ;;
  esac
}

# Remove folders SBrain may have created, but only once they are empty, so an uninstalled agent's
# config folder doesn't make it look installed on the next run.
prune_dirs() {
  local d
  [ "$dry" = 1 ] && return 0
  for d in "$HOME/.cursor/agents" "$HOME/.cursor" "${CODEX_HOME:-$HOME/.codex}/agents" "${CODEX_HOME:-$HOME/.codex}" \
           "$HOME/.copilot/agents" "$HOME/.copilot/hooks" "$HOME/.copilot" "$HOME/.config/opencode/agents" "$HOME/.config/opencode" "$HOME/.config" \
           "$HOME/.gemini/agents" "$HOME/.gemini/config/skills" "$HOME/.gemini/config" "$HOME/.gemini" \
           "$HOME/.agents/skills" "$HOME/.agents/agents" "$HOME/.agents"; do
    [ -d "$d" ] && rmdir "$d" 2>/dev/null || true
  done
}

[ "$dry" = 1 ] && say "Dry run. Nothing will change."
for t in $targets; do
  say "$t:"
  if [ "$uninstall" = 1 ]; then uninstall_target "$t"; else install_target "$t"; fi
done
if [ "$uninstall" = 1 ]; then prune_dirs; else say "Done. Each agent's adapter is in $SKILLS/skiddle-mode/references/harness/."; fi
